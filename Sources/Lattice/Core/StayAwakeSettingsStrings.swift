extension StayAwakeSettingsStrings {
    /// `<n> app(s): A, B`, in the form the language gives that count.
    func appsSummary(count: Int, names: String, _ language: AppLanguage) -> String {
        let format: String
        switch language.countAgreement {
        case .oneAndMany:
            format = count == 1 ? appsOne : appsMany
        case .byLastDigits:
            let lastTwo = count % 100, last = count % 10
            format = last == 1 && lastTwo != 11 ? appsOne
                : (2...4).contains(last) && !(12...14).contains(lastTwo) ? appsFew : appsMany
        case .byWholeNumber:
            format = count == 1 ? appsOne : (2...4).contains(count) ? appsFew : appsMany
        }
        return String(format: format, count, names)
    }
}

