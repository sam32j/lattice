extension URLSanitizerStrings {
    /// `<n> tracker(s)`, in the form the language gives that count.
    func trackerCount(_ count: Int, _ language: AppLanguage) -> String {
        let format: String
        switch language.countAgreement {
        case .oneAndMany:
            format = count == 1 ? trackerOne : trackerMany
        case .byLastDigits:
            let lastTwo = count % 100, last = count % 10
            format = last == 1 && lastTwo != 11 ? trackerOne
                : (2...4).contains(last) && !(12...14).contains(lastTwo) ? trackerFew : trackerMany
        case .byWholeNumber:
            format = count == 1 ? trackerOne : (2...4).contains(count) ? trackerFew : trackerMany
        }
        return String(format: format, count)
    }
}

