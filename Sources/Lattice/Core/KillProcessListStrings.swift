/// One plain sentence about common macOS processes for What Is This?. The
/// table is English; other languages, and processes it does not know, get
/// `partOfMacOSFormat`.
enum KillProcessDescriptions {
    static func description(for name: String, language: AppLanguage) -> String {
        specificDescription(for: name, language: language)
            ?? String(format: FeatureStrings.killProcessList(language).partOfMacOSFormat, name)
    }

    /// What the process does, when the table knows it in this language.
    static func specificDescription(for name: String, language: AppLanguage) -> String? {
        language == .enUS ? english[name.lowercased()] : nil
