/// Strings for the redesigned Kill Process list shared by Settings, the
/// floating HUD and the Dynamic Island. Same contract as the other
/// FeatureStrings structs: memberwise init in declaration order, one static
/// per language, all in this file. Counted phrases come as a one/other pair;
/// `count(_:one:other:)` picks between them.
struct KillProcessListStrings {
    let scopeApps: String
    let scopeBackground: String
    let scopeSystem: String
    let scopePorts: String
    let scopeEverything: String
    /// "All Processes" shortened for the Island's scope button.
    let scopeEverythingShort: String
    let scopeLabel: String
    let searchApps: String
    let searchBackground: String
    let searchSystem: String
    let searchPorts: String
    let searchEverything: String
    let sectionRunningFormat: String
    let helperCountOne: String
    let helperCountOther: String
    let portCountOne: String
    let portCountOther: String
    let allInterfaces: String
    let allInterfacesHelp: String
    let serviceAirPlayAudio: String
    let serviceAirPlayReceiver: String
    let serviceContinuity: String
    let serviceAirDropHandoff: String
    let serviceRemoteLogin: String
    let serviceFileSharing: String
    let serviceScreenSharing: String
    let serviceMusicSharing: String
    let servicePrinterSharing: String
    let serviceRemoteManagement: String
    let cpuFormat: String
    let chipNotResponding: String
    let chipThisApp: String
    let chipFront: String
    let chipKept: String
    let quit: String
    let stop: String
    let forceQuit: String
    let confirm: String
    let quitting: String
    let stopping: String
    let relaunch: String
    let keepRunning: String
    let showInFinder: String
    let copyPID: String
    let quitOthers: String
    let confirmAppsOne: String
    let confirmAppsOther: String
    let confirmButtonFormat: String
    let cancel: String
    let toastQuitFormat: String
    let toastAppsQuitOne: String
    let toastAppsQuitOther: String
    let toastRelaunchedFormat: String
    let toastNotRelaunchedFormat: String
    let toastCopiedPIDFormat: String
    let toastCouldNotStopFormat: String
    let reopen: String
    let emptySearchFormat: String
    let emptyScope: String
    let refresh: String
    let moreActionsFormat: String
    let copyPIDLabelFormat: String
    let helpersExpanded: String
    let helpersCollapsed: String
    let showMoreFormat: String
    let showLess: String
    let partOfMacOSFormat: String

    func count(_ value: Int, one: String, other: String) -> String {
        String(format: value == 1 ? one : other, value)
    }

    /// What a port is for, in words; a dev tool keeps its own name.
    func serviceName(_ service: KillProcessPortService) -> String {
        switch service {
        case .airPlayAudio: return serviceAirPlayAudio
        case .airPlayReceiver: return serviceAirPlayReceiver
        case .continuity: return serviceContinuity
        case .airDropAndHandoff: return serviceAirDropHandoff
        case .remoteLogin: return serviceRemoteLogin
        case .fileSharing: return serviceFileSharing
        case .screenSharing: return serviceScreenSharing
        case .musicSharing: return serviceMusicSharing
        case .printerSharing: return servicePrinterSharing
        case .remoteManagement: return serviceRemoteManagement
        case .tool(let name): return name
        }
    }

    func scopeName(_ scope: KillProcessScope) -> String {
        switch scope {
        case .apps: return scopeApps
        case .background: return scopeBackground
        case .ports: return scopePorts
        case .system: return scopeSystem
        case .everything: return scopeEverything
        }
    }

    func searchPlaceholder(_ scope: KillProcessScope) -> String {
        switch scope {
        case .apps: return searchApps
        case .background: return searchBackground
        case .ports: return searchPorts
        case .system: return searchSystem
        case .everything: return searchEverything
        }
    }
}

